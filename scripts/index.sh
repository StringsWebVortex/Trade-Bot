#!/usr/bin/env bash
# Generate audit/codebase_index.md — the fast-query knowledge layer for agents.
# Uses rg (ripgrep) and standard POSIX tools; completes in under 60 s on this repo.
# Sections are designed for grep/line-range reads, NOT whole-file reads.
#
# Usage:
#   bash scripts/index.sh                # regenerates audit/codebase_index.md
#   bash scripts/index.sh --check        # exits non-zero if committed index is stale
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="$ROOT/audit"
OUT="$OUT_DIR/codebase_index.md"
TEMP="$OUT.tmp.$$"
CHECK_MODE=false

[[ "${1:-}" == "--check" ]] && CHECK_MODE=true

mkdir -p "$OUT_DIR"
trap 'rm -f "$TEMP"' EXIT

have() { command -v "$1" >/dev/null 2>&1; }
have rg || { echo "ERROR: ripgrep (rg) is required. Install with: apt install ripgrep or brew install ripgrep" >&2; exit 1; }

BRANCH=$(git -C "$ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || echo "unknown")
COMMIT=$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo "unknown")
TIMESTAMP=$(date -u "+%Y-%m-%dT%H:%M:%SZ")

{
# ─────────────────────────────────────────────────────────────
# STATUS
# ─────────────────────────────────────────────────────────────
cat <<EOF
# Codebase Index

Auto-generated by \`scripts/index.sh\`. Never edit by hand — regenerate instead.
Agents: grep section headers or read by line range; never read the whole file.

## Status

- Generated: $TIMESTAMP
- Branch: $BRANCH
- Commit: $COMMIT
- Deep reference: \`codebase-analysis-docs/CODEBASE_KNOWLEDGE.md\` (manual, architecture-level)
- File inventory: \`codebase-analysis-docs/FILE_INDEX.md\` (SHA8, 1315 tracked paths)
- API detail: \`codebase-analysis-docs/API_REFERENCE.md\`
- Chunk ranges: \`codebase-analysis-docs/CHUNK_INDEX.md\`

EOF

# ─────────────────────────────────────────────────────────────
# MODULE MAP — one line per Python file, what it exports
# ─────────────────────────────────────────────────────────────
echo "## Module Map"
echo ""
echo "Format: \`path\` — top-level classes | functions (file:line)"
echo ""

# Collect Python source files (not tests, not migrations)
mapfile -t PY_FILES < <(git -C "$ROOT" ls-files '*.py' | grep -v '^tests/' | grep -v 'migrations' | sort)

for f in "${PY_FILES[@]}"; do
    full="$ROOT/$f"
    [[ -f "$full" ]] || continue
    # Extract class and function names defined at module level (no leading indent)
    classes=$(rg --no-filename -o "^class\s+(\w+)" "$full" --replace '$1' 2>/dev/null | tr '\n' ',' | sed 's/,$//' || true)
    fns=$(rg --no-filename -o "^def\s+(\w+)" "$full" --replace '$1' 2>/dev/null | tr '\n' ',' | sed 's/,$//' || true)
    async_fns=$(rg --no-filename -o "^async def\s+(\w+)" "$full" --replace '$1' 2>/dev/null | tr '\n' ',' | sed 's/,$//' || true)
    all_fns=""
    [[ -n "$fns" ]] && all_fns="$fns"
    [[ -n "$async_fns" ]] && { [[ -n "$all_fns" ]] && all_fns="$all_fns,$async_fns" || all_fns="$async_fns"; }
    desc=""
    [[ -n "$classes" ]] && desc="classes: $classes"
    [[ -n "$all_fns" ]] && { [[ -n "$desc" ]] && desc="$desc | fns: $all_fns" || desc="fns: $all_fns"; }
    [[ -z "$desc" ]] && desc="(no top-level definitions)"
    echo "- \`$f\` — $desc"
done
echo ""

# ─────────────────────────────────────────────────────────────
# API SURFACE — FastAPI routes
# ─────────────────────────────────────────────────────────────
echo "## API Surface"
echo ""
echo "FastAPI routes — method + path + handler + file:line"
echo ""

# Find all @router.get/post/put/delete/patch and @app.get etc.
rg --with-filename --line-number \
   '@(router|app)\.(get|post|put|delete|patch|websocket)\(' \
   "$ROOT/src" --include='*.py' 2>/dev/null | \
while IFS=: read -r file line rest; do
    rel="${file#$ROOT/}"
    path_str=$(echo "$rest" | rg -o '"[^"]+"' --max-count=1 2>/dev/null | tr -d '"' || echo "?")
    method=$(echo "$rest" | rg -o '\.(get|post|put|delete|patch|websocket)\(' 2>/dev/null | tr -d '.' | tr -d '(' || echo "?")
    echo "- $method $path_str @ $rel:$line"
done 2>/dev/null | sort || true
echo ""

# ─────────────────────────────────────────────────────────────
# SCHEMAS — Pydantic models
# ─────────────────────────────────────────────────────────────
echo "## Schemas"
echo ""
echo "Pydantic BaseModel subclasses — name + file:line"
echo ""

rg --with-filename --line-number \
   "^class\s+\w+\s*\(.*BaseModel" \
   "$ROOT/src" --include='*.py' 2>/dev/null | \
while IFS=: read -r file line rest; do
    rel="${file#$ROOT/}"
    name=$(echo "$rest" | rg -o "class\s+(\w+)" 2>/dev/null | sed 's/class //' || echo "?")
    echo "- $name @ $rel:$line"
done 2>/dev/null | sort || true
echo ""

# ─────────────────────────────────────────────────────────────
# OPEN WORK — TODO / FIXME / HACK / XXX
# ─────────────────────────────────────────────────────────────
echo "## Open Work"
echo ""
echo "TODO/FIXME/HACK/XXX markers — file:line + text"
echo ""

rg --with-filename --line-number \
   "(TODO|FIXME|HACK|XXX)[\s:]" \
   "$ROOT/src" "$ROOT/frontend/src" "$ROOT/scripts" "$ROOT/config" \
   --include='*.py' --include='*.js' --include='*.jsx' --include='*.ts' --include='*.tsx' \
   2>/dev/null | \
while IFS=: read -r file line rest; do
    rel="${file#$ROOT/}"
    text=$(echo "$rest" | sed 's/^[[:space:]]*//' | cut -c1-120)
    echo "- $rel:$line — $text"
done 2>/dev/null | sort | head -200 || true
echo ""

# ─────────────────────────────────────────────────────────────
# INCOMPLETE MODULES — stubs, pass-only bodies, NotImplemented
# ─────────────────────────────────────────────────────────────
echo "## Incomplete Modules"
echo ""
echo "Files with NotImplemented raises, pass-only function bodies, or stub markers"
echo ""

rg --with-filename --line-number \
   "(raise NotImplemented|NotImplementedError\(\)|#\s*(stub|STUB|TODO:.*implement))" \
   "$ROOT/src" --include='*.py' 2>/dev/null | \
while IFS=: read -r file line rest; do
    rel="${file#$ROOT/}"
    text=$(echo "$rest" | sed 's/^[[:space:]]*//' | cut -c1-100)
    echo "- $rel:$line — $text"
done 2>/dev/null | sort | head -150 || true
echo ""

# ─────────────────────────────────────────────────────────────
# KNOWN FAILURES — from latest audit logs
# ─────────────────────────────────────────────────────────────
echo "## Known Failures"
echo ""

AUDIT_DIR="$ROOT/audit"
if [[ -f "$AUDIT_DIR/pytest.txt" ]]; then
    echo "### pytest (last run)"
    echo '```'
    grep -E "^(FAILED|ERROR|ERRORS|short test summary)" "$AUDIT_DIR/pytest.txt" 2>/dev/null | head -40 || echo "(no failures recorded)"
    echo '```'
elif [[ -f "$ROOT/codebase-analysis-docs/PHASE_2_SOURCE_AUDIT.md" ]]; then
    echo "### Pre-existing failures (from PHASE_2_SOURCE_AUDIT.md — rerun audit.sh for current state)"
    echo ""
    grep -A2 "fail\|error\|broken\|missing" "$ROOT/codebase-analysis-docs/PHASE_2_SOURCE_AUDIT.md" 2>/dev/null | head -30 || echo "(none found)"
fi

# Always list CLAUDE.md documented pre-existing failures
cat <<'EOF'

### Documented pre-existing failures (CLAUDE.md)

- mypy: "Duplicate module named 'agent_control'" — `tests/agent_control/__init__.py` vs `scripts/agent_control.py`
- pytest collection: `.claude/hooks/pre_tool_use.py` and `_gh_contract.py` missing
- frontend: `Workspace.grid.test.jsx` assertion failures
- CI gates: pyre, Security/SUP gates, CodeQL gate fail on main

EOF

# ─────────────────────────────────────────────────────────────
# NAVIGATION — quick lookup table
# ─────────────────────────────────────────────────────────────
echo "## Navigation"
echo ""
echo "Quick lookup: topic → primary file:line"
echo ""

cat <<'EOF'
| Topic | Primary location |
|---|---|
| FastAPI app + lifespan | `src/api/main.py:1` |
| API auth + keys | `src/api/auth.py:1` |
| Access control / roles | `src/api/access_control.py:1` |
| WebSocket guard | `src/api/ws_guard.py:1` |
| Main settings / config | `src/config.py:1` |
| Main trading loop | `src/engine/orchestrator.py:1` |
| Signal computation | `src/engine/signal_engine.py:1` |
| Feature pipeline | `src/features/pipeline.py:1` |
| Market data fetcher | `src/data/fetcher.py:1` |
| SQLite storage | `src/data/storage.py:1` |
| TimescaleDB storage | `src/data/timescale_storage.py:1` |
| Live executor | `src/execution/live.py:1` |
| Order state machine | `src/execution/order_fsm.py:1` |
| Risk checks | `src/risk/` |
| Model training | `src/models/trainer.py:1` |
| Model registry | `src/models/model_registry.py:1` |
| Pydantic schemas | grep `## Schemas` in this file |
| All API routes | grep `## API Surface` in this file |
| TODO/FIXME list | grep `## Open Work` in this file |
| Architecture diagram | `codebase-analysis-docs/assets/architecture.mmd` |
| Import layering rules | `config/architecture_layers.json:1` |
| Quality registry | `config/quality_registry.json:1` |
| Math registry | `config/math_registry.json:1` |
| React dashboard | `frontend/src/App.jsx:1` |
| React API client | `frontend/src/hooks/useApi.js:1` |
| CI workflow | `.github/workflows/ci.yml:1` |
| Agent definitions | `.claude/agents/` |
EOF
echo ""

} > "$TEMP"

if $CHECK_MODE; then
    if [[ ! -f "$OUT" ]]; then
        echo "FAIL: $OUT does not exist. Run: bash scripts/index.sh" >&2
        exit 1
    fi
    # Compare ignoring the timestamp line
    if diff <(grep -v "^- Generated:" "$OUT") <(grep -v "^- Generated:" "$TEMP") >/dev/null 2>&1; then
        echo "OK: audit/codebase_index.md is up to date."
        exit 0
    else
        echo "STALE: audit/codebase_index.md differs from a fresh regeneration."
        echo "Run: bash scripts/index.sh && git add audit/codebase_index.md && git commit -m 'chore: refresh codebase index'"
        exit 1
    fi
fi

mv "$TEMP" "$OUT"
LINE_COUNT=$(wc -l < "$OUT")
echo "Generated $OUT ($LINE_COUNT lines)"
